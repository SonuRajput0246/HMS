from marshmallow import fields, validate, ValidationError, validates_schema

from src.api.schemas.common.base import BaseSchema
from src.api.schemas.fields.name import name_field
from src.api.schemas.fields.text import text_field
from src.api.schemas.fields.phone import phone_number_field
from src.api.schemas.fields.email import email_field
from src.api.schemas.common.id_schema import id_schema_factory


GetCustomerByIdSchema = id_schema_factory("id", "Customer Id")
UpsertCustomerIdSchema = id_schema_factory("id", "Customer Id", min_value=0)


class UpsertCustomerSchema(UpsertCustomerIdSchema):
    """id == 0 creates, otherwise updates.

    customer_code is NOT accepted here -- it is generated by
    DocumentSequenceService so two staff cannot create CUS-202610-00007 twice.
    Loyalty counters (loyalty_points, total_visits, total_spent, last_visit_at)
    are also absent on purpose: they are server-owned and only move through
    Customer.record_visit() / redeem_points().
    """

    name = name_field("Customer Name")
    phone = phone_number_field(required=True)
    email = email_field(required=False, allow_none=True)
    address = text_field(
        max_len=255, min_len=0, required=False, allow_none=True, label="Address"
    )
    dietary_notes = text_field(
        max_len=500, min_len=0, required=False, allow_none=True, label="Dietary Notes"
    )
    is_vip = fields.Boolean(required=False, allow_none=True)
    is_active = fields.Boolean(required=True)
    is_deleted = fields.Boolean(required=True)


class GetCustomersSchema(BaseSchema):
    page_size = fields.Integer(
        required=False, allow_none=False,
        load_default=20,
        validate=validate.Range(min=1, max=200, error="Page size must be between 1 and 200"),
        error_messages={"invalid": "Page size must be an integer"}
    )
    page_number = fields.Integer(
        required=False, allow_none=False,
        load_default=1,
        validate=validate.Range(min=1, error="Page number must be greater than 0"),
        error_messages={"invalid": "Page number must be an integer"}
    )
    is_vip = fields.Boolean(required=False, allow_none=True)
    search_value = fields.String(required=False, allow_none=True, validate=validate.Length(min=0))


class QuickCustomerSchema(BaseSchema):
    """Walk-in capture at the till.

    Deliberately only name + phone. The POS must stay fast enough to type
    before a queue builds up, so this creates the minimum viable customer and
    leaves the rest to be filled in later from the customer module.
    """
    name = name_field("Customer Name")
    phone = phone_number_field(required=True)


class LookupByPhoneSchema(BaseSchema):
    """Till-side lookup. Phone only -- no name needed to find an existing
    record."""
    phone = phone_number_field(required=True)


class RedeemPointsSchema(BaseSchema):
    """Spend loyalty points against an order.

    points is capped at 1 so a zero/negative slip cannot top up the balance;
    the service additionally rejects redeeming more than the customer holds.
    """
    id = fields.Integer(
        required=True,
        validate=validate.Range(min=1, error="Customer Id must be greater than 0"),
        error_messages={"required": "Customer Id is required", "invalid": "Invalid Customer Id"}
    )
    points = fields.Integer(
        required=True,
        validate=validate.Range(min=1, error="Points must be greater than 0"),
        error_messages={"required": "Points are required", "invalid": "Points must be an integer"}
    )